// Isolated integration check. Requires optional @electric-sql/pglite and pglite-socket.
// Never reads .env or connects to the application's database.
import 'reflect-metadata';
import assert from 'node:assert/strict';
import { readdir, readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';
import { PGLiteSocketServer } from '@electric-sql/pglite-socket';
import { PrismaPg } from '@prisma/adapter-pg';
import { PrismaClient } from '../apps/api/dist/generated/prisma/client.js';
import { NewsletterService } from '../apps/api/dist/newsletter/newsletter.service.js';
import { NewsletterWorker } from '../apps/api/dist/newsletter/newsletter.worker.js';
import { CareersController, CmsCareersController } from '../apps/api/dist/careers/careers.controller.js';
import { CvSecurity } from '../apps/api/dist/careers/cv-security.js';
const embedded = await PGlite.create();
const server = new PGLiteSocketServer({ db: embedded, port: 0, host: '127.0.0.1' });
let db;
try {
  const root = new URL('../apps/api/prisma/migrations/', import.meta.url);
  for (const entry of (await readdir(root, { withFileTypes: true })).filter((e) => e.isDirectory()).sort((a,b) => a.name.localeCompare(b.name))) await embedded.exec(await readFile(new URL(`${entry.name}/migration.sql`, root), 'utf8'));
  await server.start();
  db = new PrismaClient({ adapter: new PrismaPg({ connectionString: `postgresql://postgres:postgres@${server.getServerConn()}/postgres`, max: 1 }), transactionOptions: { maxWait: 10000, timeout: 10000 } });
  const config = { get: (key) => key === 'NODE_ENV' ? 'test' : undefined, getOrThrow: () => 'http://localhost:3000' };
  const service = new NewsletterService(db), sent = [], synced = [];
  const worker = new NewsletterWorker(db, { confirmationEnabled: true, sendConfirmation: async (message) => sent.push(message), syncContact: async (contact) => synced.push(contact) }, config);
  const input = { email: 'integration@example.test', name: 'Test person', language: 'en', source: 'integration' };
  await service.subscribe(input, 'Test consent');
  assert.equal(sent.length, 0);
  assert.equal((await db.newsletterSubscriber.findUnique({ where: { email: input.email } })).status, 'PENDING');
  await worker.process();
  assert.equal(sent.length, 1);
  const token = (url) => new URLSearchParams(new URL(url).hash.slice(1)).get('token');
  const confirm = token(sent[0].confirmationUrl), unsubscribe = token(sent[0].unsubscribeUrl);
  const stored = await db.newsletterToken.findMany();
  assert.equal(stored.length, 2); assert.ok(stored.every((t) => t.tokenHash !== confirm && t.tokenHash !== unsubscribe));
  await service.confirm(confirm);
  assert.equal((await db.newsletterSubscriber.findUnique({ where: { email: input.email } })).status, 'ACTIVE');
  await assert.rejects(service.confirm(confirm), { status: 400 });
  await worker.process(); assert.equal(synced.at(-1).status, 'ACTIVE');
  await service.unsubscribe(unsubscribe); await service.unsubscribe(unsubscribe);
  let subscriber = await db.newsletterSubscriber.findUnique({ where: { email: input.email } });
  assert.equal(subscriber.status, 'UNSUBSCRIBED'); assert.ok(subscriber.unsubscribedAt);
  await worker.process(); assert.equal(synced.at(-1).status, 'UNSUBSCRIBED');
  await service.subscribe(input, 'Consent again'); await worker.process();
  assert.equal(sent.length, 2);
  await service.unsubscribe(unsubscribe);
  assert.equal((await db.newsletterSubscriber.findUnique({ where: { email: input.email } })).status, 'PENDING');
  await service.confirm(token(sent[1].confirmationUrl));
  subscriber = await db.newsletterSubscriber.findUnique({ where: { email: input.email } });
  await service.suppress(subscriber.id, 'BOUNCED', subscriber.version, 'test-admin');
  await service.subscribe(input, 'Cannot override bounce');
  assert.equal((await db.newsletterSubscriber.findUnique({ where: { email: input.email } })).status, 'BOUNCED');
  await assert.rejects(service.suppress(subscriber.id, 'UNSUBSCRIBED', subscriber.version, 'test-admin'), { status: 409 });
  console.log('Newsletter: durable outbox, hashed tokens, double opt-in, replay, unsubscribe, re-opt-in, bounce and version checks passed');
  const admin = new CmsCareersController(db), publicApi = new CareersController(db, config, { rateLimit: async () => {}, verify: async () => {} }, new CvSecurity(config));
  const req = { cmsUser: { id: 'test-admin', role: 'SUPER_ADMIN' }, headers: {}, ip: '127.0.0.1' };
  const job = { title: 'Test role', slug: 'test-role', department: 'Engineering', location: 'Remote', employmentType: 'FULL_TIME', workMode: 'REMOTE', description: 'Test description', responsibilities: ['Build software'], requirements: ['Relevant experience'], preferredQualifications: [], status: 'PUBLISHED', publishedAt: '2026-01-01T00:00:00.000Z', closingDate: null, version: 0 };
  const created = await admin.create(job, req);
  for (const status of ['DRAFT', 'CLOSED', 'ARCHIVED']) await admin.create({ ...job, slug: status.toLowerCase(), status }, req);
  await admin.create({ ...job, slug: 'future', publishedAt: '2099-01-01T00:00:00.000Z' }, req);
  assert.equal((await publicApi.list({})).total, 1);
  for (const slug of ['draft', 'closed', 'archived', 'future']) await assert.rejects(publicApi.detail(slug), { status: 404 });
  const payload = { submissionId: randomUUID(), jobSlug: job.slug, name: 'Candidate', email: 'candidate@example.test', location: 'Test city', consent: true };
  const bytes = Buffer.from('%PDF-1.4\n1 0 obj\n<< /Type /Catalog >>\nendobj\ntrailer\n<< /Root 1 0 R >>\n%%EOF\n');
  const file = { buffer: bytes, size: bytes.length, originalname: 'cv.pdf', mimetype: 'application/pdf' };
  assert.deepEqual(await publicApi.apply({ payload: JSON.stringify(payload) }, file, req), { ok: true });
  await publicApi.apply({ payload: JSON.stringify(payload) }, file, req);
  assert.equal(await db.jobApplication.count(), 1);
  await assert.rejects(publicApi.apply({ payload: JSON.stringify({ ...payload, name: 'Changed' }) }, file, req), { status: 409 });
  const application = await db.jobApplication.findFirst();
  await admin.status(application.id, { status: 'REVIEWING', version: 1 }, req);
  await admin.note(application.id, { note: 'Internal assessment', version: 2 }, req);
  await assert.rejects(admin.status(application.id, { status: 'HIRED', version: 1 }, req), { status: 409 });
  assert.equal((await admin.history(application.id, {})).total, 3);
  const detail = await admin.application(application.id);
  assert.equal('bytes' in detail.cv, false); assert.equal('submissionHash' in detail, false);
  const publicDetail = await publicApi.detail(job.slug);
  assert.equal(JSON.stringify(publicDetail).includes('candidate@example.test'), false);
  await admin.update(created.id, { ...job, version: 1, status: 'CLOSED' }, req);
  assert.equal((await publicApi.list({})).total, 0); assert.equal(await db.jobApplication.count(), 1);
  console.log('Careers: publication filters, private applications, CV storage, retry deduplication, notes/history and conflict checks passed');
} finally { await db?.$disconnect(); await server.stop(); await embedded.close(); }
