import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const tokens = JSON.parse(
  await readFile(new URL('packages/config/design-tokens.json', root), 'utf8'),
);
const theme = [];
const variables = [];
for (const [key, value] of Object.entries(tokens.colors)) theme.push(`  --color-${key}: ${value};`);
for (const [key, value] of Object.entries(tokens.breakpoints))
  theme.push(`  --breakpoint-${key}: ${value};`);
for (const [key, value] of Object.entries(tokens.containers))
  theme.push(`  --container-${key}: ${value};`);
theme.push(
  `  --font-heading: ${tokens.fonts.heading};`,
  `  --font-sans: ${tokens.fonts.body};`,
  `  --font-mono: ${tokens.fonts.mono};`,
);
for (const [group, prefix] of [
  ['spacing', 'space'],
  ['radius', 'radius'],
  ['shadows', 'shadow'],
  ['gradients', 'gradient'],
  ['transitions', 'motion'],
  ['zIndex', 'z'],
]) {
  for (const [key, value] of Object.entries(tokens[group]))
    variables.push(`  --${prefix}-${key}: ${value};`);
}
for (const [key, value] of Object.entries(tokens.typography)) {
  for (const [property, setting] of Object.entries(value))
    variables.push(
      `  --type-${key}-${property.replace(/[A-Z]/g, (char) => '-' + char.toLowerCase())}: ${setting};`,
    );
}
const css = `/* Generated by npm run tokens:generate from design-tokens.json. */\n@theme {\n${theme.join('\n')}\n}\n:root {\n${variables.join('\n')}\n}\n`;
const destination = new URL('packages/config/tokens.css', root);
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')).replaceAll('\r\n', '\n') !== css)
    throw new Error('Design tokens are stale. Run npm run tokens:generate.');
  console.log('Design tokens are synchronized.');
} else await writeFile(destination, css);
